#!/usr/bin/env python3
"""Pack branding (owner, 2026-10-29: release prep after testing).

Writes:
  pack/kubejs/config/client.properties   KubeJS client settings: window title with the pack version, loading-screen
                                          colours in the Emberhold palette (ClientProperties, KubeJS 2001 source)
  pack/kubejs/config/packicon.png        window icon (KubeJSPaths.PACKICON; KubeJS swaps it in for Minecraft's)
  docs/branding/icon.png                 512x512 icon for the CurseForge/Modrinth project page and Prism

Prefer docs/branding/icon-source.png (painted cracked crown, opaque RGB) when present — CurseForge project
logos want a square PNG at least ~400–512px; the 128px packicon alone is too small for CF upload.
Falls back to a procedural broken-crown disc if the source file is missing.
Run by build_prism.py; pack_version comes from modpack/curseforge-mods.json.
"""
import json, math, os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = os.path.join(ROOT, "pack", "kubejs", "config")
BRANDING = os.path.join(ROOT, "docs", "branding")
ICON_SOURCE = os.path.join(BRANDING, "icon-source.png")
# Emberhold palette (same as blockbench/previews/npc-viewer.html)
BG, WALL, EMBER, GOLD, ASH, CREAM = (23, 19, 15), (44, 36, 28), (232, 147, 74), (226, 207, 138), (181, 166, 143), (239, 228, 210)


def hexc(c):
    return "%02X%02X%02X" % c


def shard(cx, top, w, h, lean):
    """A tall crown point, broken at the tip: a kite with a slanted break."""
    return [(cx - w / 2, top + h), (cx - w / 2 + lean * 0.3, top + h * 0.35), (cx + lean, top),
            (cx + w / 2 + lean * 0.2, top + h * 0.22), (cx + w / 2, top + h)]


def draw_icon(size=512):
    s = size * 2  # supersample
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # dark disc with a warm rim
    d.ellipse([s * 0.04, s * 0.04, s * 0.96, s * 0.96], fill=BG + (255,), outline=WALL + (255,), width=int(s * 0.03))
    # glow behind the crown
    glow = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse([s * 0.2, s * 0.32, s * 0.8, s * 0.86], fill=EMBER + (150,))
    img = Image.alpha_composite(img, glow.filter(ImageFilter.GaussianBlur(s * 0.07)))
    d = ImageDraw.Draw(img)
    # crown band
    band_top, band_h = s * 0.58, s * 0.13
    d.rounded_rectangle([s * 0.24, band_top, s * 0.76, band_top + band_h], radius=s * 0.02, fill=GOLD + (255,))
    for i in range(4):  # gem studs
        x = s * (0.31 + i * 0.127)
        d.ellipse([x - s * 0.022, band_top + band_h / 2 - s * 0.022, x + s * 0.022, band_top + band_h / 2 + s * 0.022], fill=EMBER + (255,))
    # five shards: the middle one whole and tallest, the others broken and leaning
    points = [(0.29, 0.40, 0.10, -0.03), (0.395, 0.30, 0.11, -0.015), (0.5, 0.17, 0.13, 0.0),
              (0.605, 0.30, 0.11, 0.015), (0.71, 0.40, 0.10, 0.03)]
    for cx, top, w, lean in points:
        poly = shard(s * cx, s * top, s * w, band_top - s * top + s * 0.01, s * lean)
        d.polygon(poly, fill=EMBER + (255,))
        # lit face
        d.polygon([poly[0], poly[1], poly[2], ((poly[0][0] + poly[-1][0]) / 2, poly[0][1])], fill=(247, 186, 120, 255))
    # a few drifting sparks
    for ang, r, rad in [(200, 0.36, 0.012), (240, 0.40, 0.009), (310, 0.37, 0.011), (335, 0.42, 0.008), (20, 0.33, 0.01)]:
        a = math.radians(ang)
        x, y = s / 2 + math.cos(a) * s * r, s * 0.5 + math.sin(a) * s * r
        d.ellipse([x - s * rad, y - s * rad, x + s * rad, y + s * rad], fill=CREAM + (230,))
    return img.resize((size, size), Image.LANCZOS)


def load_icon(size=512):
    """CurseForge-ready opaque square from painted source, else procedural fallback."""
    if os.path.isfile(ICON_SOURCE):
        src = Image.open(ICON_SOURCE).convert("RGB")
        if src.size != (size, size):
            src = src.resize((size, size), Image.LANCZOS)
        return src
    return draw_icon(size).convert("RGB")


def main():
    version = json.load(open(os.path.join(ROOT, "modpack", "curseforge-mods.json"), encoding="utf-8"))["pack_version"]
    os.makedirs(CFG, exist_ok=True)
    props = {
        "title": f"Terrestrial Tribulations {version}",
        "backgroundColor": hexc(BG), "barColor": hexc(EMBER), "barBorderColor": hexc(EMBER),
        "fmlMemoryColor": hexc(CREAM), "fmlLogColor": hexc(ASH),
    }
    with open(os.path.join(CFG, "client.properties"), "w", encoding="utf-8") as f:
        f.write("# Generated by tools/gen_branding.py. KubeJS client settings: window title and loading colours.\n")
        f.writelines(f"{k}={v}\n" for k, v in props.items())
    icon = load_icon(512)
    os.makedirs(BRANDING, exist_ok=True)
    icon.save(os.path.join(BRANDING, "icon.png"))
    icon.resize((128, 128), Image.LANCZOS).save(os.path.join(CFG, "packicon.png"))
    src_note = "icon-source.png" if os.path.isfile(ICON_SOURCE) else "procedural fallback"
    print(f"Branding: window title 'Terrestrial Tribulations {version}', pack icon, docs/branding/icon.png ({src_note})")


if __name__ == "__main__":
    main()
