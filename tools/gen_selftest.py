"""Writes pack/kubejs/config/tt_selftest.json: what the in-game self-test (server_scripts/tt_selftest.js) expects to
find loaded. Built from the pack's own data, so it stays in step with the generators:
items (design/weapons/weapons.json), Epic Fight weapon capabilities (data/tt/capabilities/weapons/), Palladium
powers (data/tt/palladium/powers/), Passive Skill Tree trees and skills (data/tt/skill_trees/, data/tt/skills/),
story-gate namespaces, origins and layers (data/tt/origins/, data/*/origin_layers/), dimension-gate
dimensions (kubejs/config/tt_story_gates.json). Run by build_prism.py."""
import json
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KJ = os.path.join(ROOT, "pack", "kubejs")


def names(path, ext=".json"):
    p = os.path.join(KJ, path)
    return sorted(f[:-len(ext)] for f in os.listdir(p) if f.endswith(ext)) if os.path.isdir(p) else []


weapons = json.load(open(os.path.join(ROOT, "design", "weapons", "weapons.json")))["weapons"]
gates = json.load(open(os.path.join(KJ, "config", "tt_story_gates.json")))
layers = ["tt:" + n for n in names("data/tt/origin_layers")] + ["origins:" + n for n in names("data/origins/origin_layers")]
# Everything the quest book points at (tools/gen_quests.py output): items, kill-task entities, dimensions
qdir = os.path.join(ROOT, "pack", "config", "ftbquests", "quests", "chapters")
snbt = "".join(open(os.path.join(qdir, f)).read() for f in sorted(os.listdir(qdir)) if f.endswith(".snbt"))
quest_items = sorted(set(re.findall(r'id: "([a-z0-9_.-]+:[a-z0-9_/.-]+)" \}', snbt)))
quest_entities = sorted(set(re.findall(r'entity: "([^"]+)"', snbt)))
pdir = os.path.join(KJ, "data", "tt", "easy_npc", "preset")
presets = "".join(open(os.path.join(r, f), encoding="utf-8").read() for r, _d, fs in os.walk(pdir) for f in fs)
npc_trade_items = sorted(set(re.findall(r'Count:\d+b,id:"([^"]+)"', presets)))
quest_dims = sorted(set(re.findall(r'dimension: "([^"]+)"', snbt)))
out = {
    "_comment": "Generated by tools/gen_selftest.py; don't edit. Read by server_scripts/tt_selftest.js (/kubejs custom_command tt_selftest).",
    "items": ["tt:" + w["id"] for w in weapons],
    "ef_weapons": ["tt:" + n for n in names("data/tt/capabilities/weapons")],
    "powers": ["tt:" + n for n in names("data/tt/palladium/powers")],
    "origins": ["tt:" + n for n in names("data/tt/origins")],
    "layers": layers,
    "skill_trees": [json.load(open(os.path.join(KJ, "data", "tt", "skill_trees", n + ".json")))["id"] for n in names("data/tt/skill_trees")],
    "skills": ["tt:" + n for n in names("data/tt/skills")],
    "gate_namespaces": sorted({ns for g in gates.get("gates", []) for ns in g.get("namespaces", [])}),
    "quest_items": quest_items,
    "quest_entities": quest_entities,
    "npc_trade_items": npc_trade_items,
    "quest_dimensions": quest_dims,
    "npc_sites": sorted(json.load(open(os.path.join(KJ, "config", "tt_npc_sites.json")))["sites"]),
    "lore_entities": sorted(json.load(open(os.path.join(KJ, "config", "tt_boss_lore.json")))["bosses"]),
    "dimensions": sorted({d for g in gates.get("dimension_gates", {}).get("gates", []) for d in g["dimensions"]}),
    # every quest keeps the ID we generated (FTB Quests replaces IDs it can't parse; 2026-10-30 desktop test)
    "quest_ids": sorted({m for p in glob.glob(os.path.join(os.path.dirname(KJ), "config", "ftbquests", "quests", "chapters", "*.snbt"))
                         for m in re.findall(r'\n\t\t\{\n\t\t\tid: "([0-9A-F]{16})"\n\t\t\ttitle:', open(p, encoding="utf-8").read())}),
}
with open(os.path.join(KJ, "config", "tt_selftest.json"), "w") as f:
    json.dump(out, f, indent=2)
    f.write("\n")
print(f"Self-test list: {len(out['items'])} items, {len(out['ef_weapons'])} EF weapons, {len(out['powers'])} powers, "
      f"{len(out['origins'])} origins, {len(quest_items)} quest items, {len(quest_entities)} quest entities, {len(out['skills'])} skills, {len(out['layers'])} layers, {len(out['dimensions'])} dimensions")
